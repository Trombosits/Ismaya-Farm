-- ============================================================================
-- Feed module: ensure item table, RLS policies and grants
--
-- The live database drifted from `20261104000000_init_schema.sql`:
--   * the purchase item table is named `feed_purchases_items` there (the init
--     schema and the app previously assumed `feed_purchase_items`);
--   * the feed tables had row level security enabled without the permissive
--     dev policy, so every write from the app failed with 42501.
--
-- This migration makes the plural table the canonical one, backfills any rows
-- from the old singular table when it happens to exist, and re-applies the
-- same dev-only policy/grant setup used by the init schema. Every step checks
-- the current state first, so it is safe to re-run.
--
-- SECURITY NOTE: the policies below are permissive by design while
-- authentication is not implemented. Replace them with auth-based policies
-- before production.
-- ============================================================================

create table if not exists public.feed_purchases_items (
  id           bigint generated by default as identity primary key,
  purchase_id  bigint not null references public.feed_purchases (id) on delete cascade,
  feed_type_id bigint not null references public.feed_types (id) on delete restrict,
  quantity     numeric(12, 2) not null default 0,
  unit_price   numeric(14, 2) not null default 0,
  subtotal     numeric(14, 2) not null default 0
);

create index if not exists feed_purchases_items_purchase_id_idx
  on public.feed_purchases_items (purchase_id);

create index if not exists feed_purchases_items_feed_type_id_idx
  on public.feed_purchases_items (feed_type_id);

-- If the old singular table exists, copy its rows over, then drop it so there
-- is only one source of truth.
do $$
begin
  if to_regclass('public.feed_purchase_items') is not null then
    insert into public.feed_purchases_items
      (purchase_id, feed_type_id, quantity, unit_price, subtotal)
    select
      s.purchase_id, s.feed_type_id, s.quantity, s.unit_price, s.subtotal
    from public.feed_purchase_items s
    where not exists (
      select 1
      from public.feed_purchases_items d
      where d.purchase_id = s.purchase_id
        and d.feed_type_id = s.feed_type_id
        and d.quantity = s.quantity
        and d.unit_price = s.unit_price
        and d.subtotal = s.subtotal
    );

    drop table public.feed_purchase_items;
  end if;
end $$;

do $$
declare
  tbl text;
begin
  foreach tbl in array array[
    'suppliers',
    'feed_types',
    'feed_purchases',
    'feed_purchases_items',
    'feed_inventory_transactions'
  ]
  loop
    execute format('alter table public.%I enable row level security', tbl);
    execute format(
      'drop policy if exists %I on public.%I',
      'dev_all_' || tbl, tbl
    );
    execute format(
      'create policy %I on public.%I for all to anon, authenticated using (true) with check (true)',
      'dev_all_' || tbl, tbl
    );
  end loop;
end $$;

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.suppliers to anon, authenticated;
grant select, insert, update, delete on public.feed_types to anon, authenticated;
grant select, insert, update, delete on public.feed_purchases to anon, authenticated;
grant select, insert, update, delete on public.feed_purchases_items to anon, authenticated;
grant select, insert, update, delete on public.feed_inventory_transactions to anon, authenticated;

grant usage, select on all sequences in schema public to anon, authenticated;

notify pgrst, 'reload schema';
