-- ============================================================================
-- ISMAYA Farm — initial schema
-- Aligned to the implemented frontend (see docs discussion).
--
-- Notes:
--   * No soft delete (Deleted_at removed) — hard deletes + status.
--   * livestock_species / livestock_breeds have NO is_active.
--   * livestock_batches is general (all species), not only poultry.
--   * livestock_batch_transactions kept for a future batch-movement feature.
--   * livestock_death_records added for mortality reporting.
-- ============================================================================

-- ---------------------------------------------------------------- users
create table if not exists public.users (
  id            bigint generated by default as identity primary key,
  name          varchar(150) not null,
  email         varchar(150) not null unique,
  password_hash text not null,
  role          varchar(30) not null default 'operator'
                check (role in ('admin', 'operator', 'viewer')),
  is_active     boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- ------------------------------------------------------------- suppliers
create table if not exists public.suppliers (
  id         bigint generated by default as identity primary key,
  name       varchar(150) not null,
  phone      varchar(30),
  address    text,
  notes      text,
  is_active  boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ------------------------------------------------------ livestock master
create table if not exists public.livestock_species (
  id         bigint generated by default as identity primary key,
  name       varchar(100) not null,
  code       varchar(20) not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.livestock_breeds (
  id         bigint generated by default as identity primary key,
  species_id bigint not null references public.livestock_species (id) on delete restrict,
  name       varchar(100) not null,
  code       varchar(20) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (species_id, code)
);

create index if not exists livestock_breeds_species_id_idx on public.livestock_breeds (species_id);

-- Guarantee the uniqueness the UI relies on (safe if already present).
create unique index if not exists livestock_species_code_key
  on public.livestock_species (code);
create unique index if not exists livestock_breeds_species_id_code_key
  on public.livestock_breeds (species_id, code);

-- --------------------------------------------------- individual livestock
create table if not exists public.livestock (
  id               bigint generated by default as identity primary key,
  tag_code         varchar(30) not null unique,
  species_id       bigint not null references public.livestock_species (id) on delete restrict,
  breed_id         bigint references public.livestock_breeds (id) on delete restrict,
  sex              varchar(10) not null check (sex in ('male', 'female')),
  birth_date       date not null,
  acquisition_date date not null,
  acquisition_type varchar(15) not null
                   check (acquisition_type in ('born', 'purchased', 'gift')),
  status           varchar(15) not null default 'active'
                   check (status in ('active', 'sold', 'dead', 'transferred')),
  mother_id        bigint references public.livestock (id) on delete set null,
  father_id        bigint references public.livestock (id) on delete set null,
  notes            text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create index if not exists livestock_species_id_idx on public.livestock (species_id);
create index if not exists livestock_breed_id_idx on public.livestock (breed_id);

-- --------------------------------------------------------- livestock batches
create table if not exists public.livestock_batches (
  id               bigint generated by default as identity primary key,
  batch_code       varchar(30) not null unique,
  species_id       bigint not null references public.livestock_species (id) on delete restrict,
  breed_id         bigint references public.livestock_breeds (id) on delete restrict,
  quantity         integer not null default 0,
  acquisition_date date not null,
  acquisition_type varchar(15) not null
                   check (acquisition_type in ('born', 'purchased', 'gift')),
  status           varchar(15) not null default 'active'
                   check (status in ('active', 'sold', 'dead', 'transferred')),
  notes            text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create index if not exists livestock_batches_species_id_idx on public.livestock_batches (species_id);

create table if not exists public.livestock_batch_transactions (
  id               bigint generated by default as identity primary key,
  batch_id         bigint not null references public.livestock_batches (id) on delete cascade,
  transaction_type varchar(10) not null check (transaction_type in ('in', 'out')),
