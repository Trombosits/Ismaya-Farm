-- ------------------------------------------------------- updated_at trigger
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare
  tbl text;
begin
  for tbl in
    select c.table_name
    from information_schema.columns c
    where c.table_schema = 'public'
      and c.column_name = 'updated_at'
  loop
    execute format(
      'drop trigger if exists %I on public.%I',
      'set_updated_at_' || tbl, tbl
    );
    execute format(
      'create trigger %I before update on public.%I for each row execute function public.set_updated_at()',
      'set_updated_at_' || tbl, tbl
    );
  end loop;
end $$;

-- ============================================================================
-- SECURITY (DEV ONLY)
-- Permissive policies so the prototype works with the publishable (anon) key
-- while authentication is not implemented yet.
